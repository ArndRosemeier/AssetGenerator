_BITMAPS = {
    ch: np.array([[c == "#" for c in row] for row in rows], dtype=bool) for ch, rows in _GLYPHS.items()
}


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * 6 * scale


def draw_text(
    image: np.ndarray, text: str, x: int, y: int, color: tuple[float, float, float], scale: int = 1
) -> None:
    """Draw `text` (upper-cased; unknown characters as '?') with its top-left corner at (x, y)."""
    height, width = image.shape[:2]
    for i, ch in enumerate(text.upper()):
        bitmap = _BITMAPS.get(ch, _BITMAPS["?"])
        if scale > 1:
            bitmap = bitmap.repeat(scale, axis=0).repeat(scale, axis=1)
        x0 = x + i * 6 * scale
        rows, cols = np.nonzero(bitmap)
        rows, cols = rows + y, cols + x0
        keep = (rows >= 0) & (rows < height) & (cols >= 0) & (cols < width)
        image[rows[keep], cols[keep]] = color
